using System;
using System.Globalization;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Media;

namespace McpBridge.Controls;

public static class AutoToolTipBehavior
{
    public static readonly DependencyProperty FullTextProperty =
        DependencyProperty.RegisterAttached(
            "FullText",
            typeof(string),
            typeof(AutoToolTipBehavior),
            new FrameworkPropertyMetadata(null, OnFullTextChanged));

    public static string? GetFullText(DependencyObject obj) => (string?)obj.GetValue(FullTextProperty);
    public static void SetFullText(DependencyObject obj, string? value) => obj.SetValue(FullTextProperty, value);

    private static void OnFullTextChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not TextBlock textBlock) return;

        textBlock.ToolTipOpening -= TextBlock_ToolTipOpening;

        if (!string.IsNullOrWhiteSpace(e.NewValue as string))
        {
            if (textBlock.ToolTip == null)
            {
                textBlock.ToolTip = " ";
            }
            textBlock.ToolTipOpening += TextBlock_ToolTipOpening;
        }
        else
        {
            textBlock.ToolTip = null;
        }
    }

    private static void TextBlock_ToolTipOpening(object sender, ToolTipEventArgs e)
    {
        if (sender is not TextBlock textBlock) return;

        var fullText = GetFullText(textBlock);
        if (string.IsNullOrWhiteSpace(fullText))
        {
            e.Handled = true;
            return;
        }

        if (!IsTextTrimmed(textBlock))
        {
            e.Handled = true;
            return;
        }

        if (textBlock.ToolTip is not ToolTip toolTip || toolTip.Tag as string != "AutoGenerated")
        {
            var style = textBlock.TryFindResource("McpTableCellToolTipStyle") as Style;
            toolTip = new ToolTip
            {
                Style = style,
                Tag = "AutoGenerated"
            };
            textBlock.ToolTip = toolTip;
        }

        toolTip.Content = fullText;
    }

    private static bool IsTextTrimmed(TextBlock textBlock)
    {
        if (textBlock.ActualWidth <= 0) return false;

        var typeface = new Typeface(
            textBlock.FontFamily,
            textBlock.FontStyle,
            textBlock.FontWeight,
            textBlock.FontStretch);

        double dpi = 1.0;
        try
        {
            dpi = VisualTreeHelper.GetDpi(textBlock).PixelsPerDip;
        }
        catch { }

        var formattedText = new FormattedText(
            textBlock.Text ?? string.Empty,
            CultureInfo.CurrentCulture,
            textBlock.FlowDirection,
            typeface,
            textBlock.FontSize,
            Brushes.Black,
            dpi);

        return formattedText.Width > textBlock.ActualWidth + 1.0;
    }
}
